window.SWK_LANG = {
  current: localStorage.getItem('swk_lang') || 'en',
  t(key, vars = {}) {
    let text = (window.SWK_I18N[this.current] && window.SWK_I18N[this.current][key]) || (window.SWK_I18N.en && window.SWK_I18N.en[key]) || key;
    return String(text).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  },
  apply(root = document) {
    document.documentElement.lang = this.current === 'zh' ? 'zh-Hans' : this.current;
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = this.t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = this.t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = this.t(el.dataset.i18nTitle); });
    document.querySelectorAll('.lang-select').forEach(s => { s.value = this.current; });
    window.dispatchEvent(new CustomEvent('swk-language-applied', { detail: { language: this.current } }));
  },
  set(lang) {
    if (!window.SWK_I18N[lang]) lang = 'en';
    this.current = lang;
    localStorage.setItem('swk_lang', lang);
    this.apply();
  },
  init() {
    if (!window.SWK_I18N[this.current]) this.current = 'en';
    document.querySelectorAll('.lang-select').forEach(select => {
      select.value = this.current;
      if (select.dataset.swkLangBound !== '1') {
        select.dataset.swkLangBound = '1';
        select.addEventListener('change', e => this.set(e.target.value));
      }
    });
    this.apply();
  }
};
window.t = (key, vars) => window.SWK_LANG.t(key, vars);
